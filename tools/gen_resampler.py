#!/usr/bin/env python3
"""Generate engine/resampler_table.c: the filter of the 20 kHz -> 44.1 kHz resampler.

The resampler is a polyphase FIR: a Kaiser-windowed sinc, 16 taps wide at the
input rate, tabulated at 64 fractional positions (plus one closing row) and
interpolated linearly between rows. Each row is normalised to sum to exactly
1.0 in Q15, so a constant input comes out as the same constant.

Usage: python tools/gen_resampler.py            (rewrites engine/resampler_table.c)
       python tools/gen_resampler.py --response  (prints the frequency response)
"""
import math
import os
import sys

TAPS = 16        # input samples spanned
PHASES = 64      # table rows per input sample
CUTOFF = 0.46    # -6 dB point, as a fraction of the input rate (9.2 kHz)
BETA = 6.0       # Kaiser window shape: about 60 dB of stopband
ONE = 1 << 15


def bessel_i0(x):
    total, term, k = 1.0, 1.0, 1
    while term > 1e-12 * total:
        term *= (x / (2 * k)) ** 2
        total += term
        k += 1
    return total


def tap(distance):
    """Filter value `distance` input samples away from the output instant."""
    half = TAPS / 2
    if abs(distance) >= half:
        return 0.0
    x = 2 * CUTOFF * distance
    sinc = 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)
    window = bessel_i0(BETA * math.sqrt(1 - (distance / half) ** 2)) / bessel_i0(BETA)
    return 2 * CUTOFF * sinc * window


def row(phase):
    """Coefficients for an output `phase`/PHASES of the way from input sample
    TAPS/2-1 to input sample TAPS/2, oldest input first."""
    frac = phase / PHASES
    real = [tap((t - (TAPS // 2 - 1)) - frac) for t in range(TAPS)]
    scale = ONE / sum(real)
    q = [int(round(v * scale)) for v in real]
    # put the rounding error on the largest tap so the row sums to exactly 1.0
    q[max(range(TAPS), key=lambda i: q[i])] += ONE - sum(q)
    return q


def table():
    return [row(p) for p in range(PHASES + 1)]


def response(freq_hz, in_rate=20000.0):
    """Gain in dB at freq_hz of the (interpolated, quantised) filter, seen as a
    continuous-time impulse response sampled finely."""
    rows = table()
    over = 441
    re = im = 0.0
    for t in range(TAPS):
        for k in range(over):
            pos = k * PHASES / over
            i = int(pos)
            f = pos - i
            c = (rows[i][t] + (rows[i + 1][t] - rows[i][t]) * f) / ONE
            d = (t - (TAPS // 2 - 1)) - k / over
            angle = 2 * math.pi * freq_hz / in_rate * d
            re += c * math.cos(angle)
            im += c * math.sin(angle)
    mag = math.hypot(re, im) / over
    return 20 * math.log10(max(mag, 1e-9))


def main():
    if "--response" in sys.argv:
        for f in (100, 1000, 3000, 5000, 6000, 7000, 8000, 9000, 9200, 10000,
                  11000, 12000, 13000, 15000, 17000, 19000, 25000, 31000, 39000):
            print("%6d Hz  %7.2f dB" % (f, response(f)))
        return
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "resampler_table.c")
    lines = [
        "/* Generated by tools/gen_resampler.py. Do not edit by hand.",
        " *",
        " * Kaiser-windowed sinc, %d taps, %d phases (plus a closing row), Q15," % (TAPS, PHASES),
        " * cutoff %.2f of the input rate, beta %.1f. Each row sums to 32768." % (CUTOFF, BETA),
        " */",
        '#include "resampler.h"',
        "",
        "const int16_t rs_table[RS_PHASES + 1][RS_TAPS] = {",
    ]
    for r in table():
        lines.append("    { " + ", ".join("%6d" % v for v in r) + " },")
    lines += ["};", ""]
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
