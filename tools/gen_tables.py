#!/usr/bin/env python3
"""Generate engine/vt_tables.c: the two Propeller ROM lookup tables VocalTract uses.

On the Propeller these live in the mask ROM:

    $D000  antilog table, 2048 words: round((2^(i/2048) - 1) * 65536)
    $E000  sine table,    2049 words: round(sin(i/2048 * 90deg) * 65535)

Both formulas reproduce the real P8X32A ROM image word for word (checked
against hub_rom_high.hex from parallaxinc/Propeller_1_Design).

Usage: python tools/gen_tables.py            (rewrites engine/vt_tables.c)
"""
import math
import os

ANTILOG_LEN = 2048
SINE_LEN = 2049


def antilog_table():
    return [int(math.floor((2.0 ** (i / 2048.0) - 1.0) * 65536.0 + 0.5)) & 0xFFFF
            for i in range(ANTILOG_LEN)]


def sine_table():
    return [min(int(math.floor(math.sin(i / 2048.0 * math.pi / 2.0) * 65535.0 + 0.5)), 0xFFFF)
            for i in range(SINE_LEN)]


def _emit(name, values):
    lines = ["const uint16_t %s[%d] = {" % (name, len(values))]
    for i in range(0, len(values), 12):
        lines.append("    " + ", ".join("0x%04X" % v for v in values[i:i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "vt_tables.c")
    text = "\n".join([
        "/* Generated by tools/gen_tables.py. Do not edit by hand.",
        " *",
        " * Copies of the Propeller P8X32A ROM antilog ($D000) and sine ($E000) tables.",
        " */",
        '#include "vt_tables.h"',
        "",
        _emit("vt_antilog_table", antilog_table()),
        "",
        _emit("vt_sine_table", sine_table()),
        "",
    ])
    with open(out, "w", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
